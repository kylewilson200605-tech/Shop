    private void displayBasketProducts() {
    DefaultTableModel model =
        (DefaultTableModel) tblBasket.getModel();

    model.setRowCount(0);

    for (OrderLine line : basketOrder.getOrderLines().values()) {
        Object[] row = {
            line.getProduct().getProductName(),
            line.getQuantity(),
            line.getProduct().getPrice(),
            line.getLineTotal()
        };

        model.addRow(row);
    }
   }

